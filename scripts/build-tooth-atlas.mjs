/**
 * Reads public/assets/teeth/<FDI>.stl (never writes them) and writes lib/client/cad/tooth-atlas.js:
 * per tooth its cervical rim centre, occlusal / mesial / facial directions in the file's arch frame,
 * crown size, and an occlusal outline used by the appointment chart.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { parseBinarySTL, V, vertexAt } from "../lib/client/cad/mesh.js";
import { shellRim } from "../lib/client/cad/tooth-library-stl.js";

const FDI = [1, 2, 3, 4].flatMap(q => Array.from({ length: 8 }, (_, i) => q * 10 + i + 1));
const raw = {};
for (const fdi of FDI) {
  const buf = readFileSync(new URL(`../public/assets/teeth/${fdi}.stl`, import.meta.url));
  const mesh = parseBinarySTL(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const { loop } = shellRim(mesh.positions, mesh.indices);
  const n = mesh.positions.length / 3;
  let c = [0, 0, 0];
  for (let i = 0; i < n; i++) c = V.add(c, vertexAt(mesh.positions, i));
  c = V.mul(c, 1 / n);
  let r = [0, 0, 0];
  for (const v of loop) r = V.add(r, vertexAt(mesh.positions, v));
  r = V.mul(r, 1 / loop.length);
  raw[fdi] = { mesh, centroid: c, rim: r, occlusal: V.norm(V.sub(c, r)) };
}

const round = (a, k = 3) => a.map(x => Number(x.toFixed(k)));
const atlas = {};
for (const fdi of FDI) {
  const q = Math.floor(fdi / 10), n = fdi % 10;
  const t = raw[fdi];
  const toward = n === 1 ? (q === 1 ? 21 : q === 2 ? 11 : q === 3 ? 41 : 31) : fdi - 1;
  const occ = t.occlusal;
  const d = V.sub(raw[toward].centroid, t.centroid);
  const mesial = V.norm(V.sub(d, V.mul(occ, V.dot(d, occ))));
  const jaw = FDI.filter(f => (q <= 2) === (Math.floor(f / 10) <= 2));
  const archCenter = V.mul(jaw.reduce((s, f) => V.add(s, raw[f].centroid), [0, 0, 0]), 1 / jaw.length);
  let facial = V.cross(occ, mesial);
  if (V.dot(facial, V.sub(t.centroid, archCenter)) < 0) facial = V.mul(facial, -1);
  // Occlusal outline: farthest point per angle around the occlusal axis, seen from the chewing side.
  const bins = 64, far = new Float64Array(bins);
  let height = 0;
  const { positions } = t.mesh;
  for (let i = 0; i < positions.length / 3; i++) {
    const p = V.sub(vertexAt(positions, i), t.rim);
    const u = V.dot(p, mesial), w = V.dot(p, facial);
    height = Math.max(height, V.dot(p, occ));
    const b = Math.floor(((Math.atan2(w, u) + Math.PI) / (2 * Math.PI)) * bins) % bins;
    far[b] = Math.max(far[b], Math.hypot(u, w));
  }
  const smooth = Array.from(far, (_, i) => (far[(i + bins - 1) % bins] + 2 * far[i] + far[(i + 1) % bins]) / 4);
  const outline = smooth.map((rad, i) => {
    const a = ((i + 0.5) / bins) * 2 * Math.PI - Math.PI;
    return [Number((Math.cos(a) * rad).toFixed(2)), Number((Math.sin(a) * rad).toFixed(2))];
  });
  const md = Math.max(...outline.map(p => p[0])) - Math.min(...outline.map(p => p[0]));
  const bl = Math.max(...outline.map(p => p[1])) - Math.min(...outline.map(p => p[1]));
  atlas[fdi] = {
    file: `${fdi}.stl`, rim: round(t.rim), centroid: round(t.centroid),
    occlusal: round(occ, 5), mesial: round(mesial, 5), facial: round(facial, 5),
    md: Number(md.toFixed(2)), bl: Number(bl.toFixed(2)), height: Number(height.toFixed(2)), outline,
  };
}

const out = `/** Generated by scripts/build-tooth-atlas.mjs from public/assets/teeth/*.stl. Do not edit by hand.
 * Frames are in the shared arch frame of those files: rim = cervical opening centre (mm),
 * occlusal / mesial / facial are unit vectors; outline is the occlusal silhouette in (mesial, facial) mm. */
export const TOOTH_ATLAS = ${JSON.stringify(atlas)};
`;
writeFileSync(new URL("../lib/client/cad/tooth-atlas.js", import.meta.url), out);
console.log(`Wrote tooth-atlas.js for ${FDI.length} teeth.`);
